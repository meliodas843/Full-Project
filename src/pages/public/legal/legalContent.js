// Chapter numbers as written in Mongolian contracts: "НЭГ", "ХОЁР" …
const ONES = ["", "нэг", "хоёр", "гурав", "дөрөв", "тав", "зургаа", "долоо", "найм", "ес"];

export function chapterNumber(n) {
  if (n < 10) return ONES[n].toUpperCase();
  if (n === 10) return "АРАВ";
  return `арван ${ONES[n - 10]}`.toUpperCase();
}

